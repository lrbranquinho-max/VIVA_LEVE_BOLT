const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');

let db;
const userId = '10000000-0000-4000-8000-000000000001';
const sessionId = '20000000-0000-4000-8000-000000000001';

before(async () => {
  db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth;
    create table auth.users(id uuid primary key, email text);
    insert into auth.users values ('${userId}','cliente@example.invalid');
    create function public.is_viva_leve_admin() returns boolean language sql stable as $$ select false $$;
    create table public.produtos(id bigint primary key, nome text);
    create table public.loja_acessos(id bigint generated by default as identity primary key, sessao_id uuid unique not null, acessado_em timestamptz default now());
    create table public.pedidos(
      id bigint generated by default as identity primary key, cliente_id uuid references auth.users(id),
      itens jsonb default '[]', pedido_origem_id bigint, tipo_venda text default 'online', pagamento_status text,
      credito_valor_original numeric, valor_total numeric, total numeric, meio_pagamento text,
      pago_em timestamptz, criado_em timestamptz default now(), updated_at timestamptz default now()
    );
  `);
  await db.exec(fs.readFileSync(path.join(__dirname, '../supabase/migrations/20261022155351_meta_conversoes_atribuicao_funil.sql'), 'utf8'));
});

after(async () => { await db?.close(); });

test('migration de atribuição executa e cria Purchase uma única vez após aprovação', async () => {
  await db.query(`insert into loja_acessos(sessao_id,meta_consent,utm_source,utm_campaign,first_touch,last_touch)
    values($1,true,'meta','campanha-teste','{"utm_source":"meta"}','{"utm_source":"meta","utm_campaign":"campanha-teste"}')`, [sessionId]);
  const order = (await db.query(`insert into pedidos(cliente_id,itens,pagamento_status,valor_total,meio_pagamento,analytics_sessao_id)
    values($1,'[{"id":"7","nome":"Marmita","quantidade":2}]','pending',49.90,'mercado_pago',$2) returning id`, [userId, sessionId])).rows[0];
  assert.equal((await db.query("select count(*)::int n from loja_eventos where event_name='purchase'")).rows[0].n, 0);
  await db.query("update pedidos set pagamento_status='approved', pago_em=now() where id=$1", [order.id]);
  await db.query("update pedidos set pagamento_status='approved', updated_at=now() where id=$1", [order.id]);
  const events = (await db.query("select * from loja_eventos where event_name='purchase'")).rows;
  assert.equal(events.length, 1);
  assert.equal(Number(events[0].propriedades.value), 49.9);
  assert.equal(events[0].propriedades.currency, 'BRL');
  assert.equal(events[0].propriedades.meta_consent, true);
});

