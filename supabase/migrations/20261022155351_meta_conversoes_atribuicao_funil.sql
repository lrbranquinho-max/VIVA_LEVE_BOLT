create or replace function private.registrar_purchase_analytics()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_consent boolean := false;
  v_valor numeric := round(coalesce(new.credito_valor_original, new.valor_total, new.total, 0), 2);
  v_content_ids jsonb := '[]'::jsonb;
  v_content_names jsonb := '[]'::jsonb;
  v_num_items integer := 0;
begin
  if new.pedido_origem_id is not null
     or coalesce(new.tipo_venda, 'online') <> 'online'
     or coalesce(new.pagamento_status, '') <> 'approved'
     or (tg_op = 'UPDATE' and coalesce(old.pagamento_status, '') = 'approved') then
    return new;
  end if;

  if new.analytics_sessao_id is not null then
    select coalesce(meta_consent, false)
      into v_consent
      from public.loja_acessos
     where sessao_id = new.analytics_sessao_id;
  end if;

  if jsonb_typeof(new.itens) = 'array' then
    select
      coalesce(jsonb_agg(distinct item->>'id') filter (where nullif(item->>'id', '') is not null), '[]'::jsonb),
      coalesce(jsonb_agg(distinct item->>'nome') filter (where nullif(item->>'nome', '') is not null), '[]'::jsonb),
      coalesce(sum(greatest(coalesce(nullif(item->>'quantidade', '')::integer, 1), 1)), 0)::integer
      into v_content_ids, v_content_names, v_num_items
      from jsonb_array_elements(new.itens) item;
  end if;

  insert into public.loja_eventos (
    event_name, sessao_id, user_id, pedido_id, pagina, origem, propriedades, ocorrido_em
  ) values (
    'purchase', new.analytics_sessao_id, new.cliente_id, new.id,
    '/pagamento/sucesso', 'server',
    jsonb_build_object(
      'value', v_valor,
      'currency', 'BRL',
      'content_ids', v_content_ids,
      'content_name', v_content_names,
      'content_type', 'product',
      'num_items', v_num_items,
      'payment_method', new.meio_pagamento,
      'meta_consent', v_consent
    ),
    coalesce(new.pago_em, now())
  ) on conflict do nothing;

  return new;
end;
$$;

revoke all on function private.registrar_purchase_analytics() from public, anon, authenticated;

drop trigger if exists pedidos_registrar_purchase_analytics on public.pedidos;
create trigger pedidos_registrar_purchase_analytics
after insert or update of pagamento_status on public.pedidos
for each row execute function private.registrar_purchase_analytics();

create or replace view public.vw_funil_loja_diario
with (security_invoker = true)
as
with sessoes as (
  select
    (acessado_em at time zone 'America/Sao_Paulo')::date as dia,
    coalesce(nullif(utm_source, ''), 'direto') as origem,
    coalesce(nullif(utm_campaign, ''), '(sem campanha)') as campanha,
    count(*) as sessoes,
    count(*) filter (
      where lower(coalesce(utm_source, '')) in ('facebook', 'instagram', 'meta', 'fb')
         or nullif(fbclid, '') is not null or nullif(fbc, '') is not null
    ) as sessoes_meta
  from public.loja_acessos
  group by 1, 2, 3
), eventos as (
  select
    (e.ocorrido_em at time zone 'America/Sao_Paulo')::date as dia,
    coalesce(nullif(a.utm_source, ''), 'direto') as origem,
    coalesce(nullif(a.utm_campaign, ''), '(sem campanha)') as campanha,
    count(*) filter (where e.event_name = 'product_view') as produtos_visualizados,
    count(*) filter (where e.event_name = 'add_to_cart') as adicoes_carrinho,
    count(distinct e.sessao_id) filter (where e.event_name = 'add_to_cart') as sessoes_carrinho,
    count(*) filter (where e.event_name = 'checkout_started') as checkouts_iniciados,
    count(distinct e.sessao_id) filter (where e.event_name = 'checkout_started') as sessoes_checkout,
    count(*) filter (where e.event_name = 'payment_started') as pagamentos_iniciados,
    count(*) filter (where e.event_name = 'whatsapp_click') as cliques_whatsapp,
    count(*) filter (where e.event_name = 'instagram_click') as cliques_instagram
  from public.loja_eventos e
  left join public.loja_acessos a on a.sessao_id = e.sessao_id
  group by 1, 2, 3
), pedidos_criados as (
  select
    (p.criado_em at time zone 'America/Sao_Paulo')::date as dia,
    coalesce(nullif(p.analytics_last_touch->>'utm_source', ''), 'direto') as origem,
    coalesce(nullif(p.analytics_last_touch->>'utm_campaign', ''), '(sem campanha)') as campanha,
    count(*) as pedidos_criados
  from public.pedidos p
  where p.pedido_origem_id is null and coalesce(p.tipo_venda, 'online') = 'online'
  group by 1, 2, 3
), pagamentos as (
  select
    (coalesce(p.pago_em, p.updated_at, p.criado_em) at time zone 'America/Sao_Paulo')::date as dia,
    coalesce(nullif(p.analytics_last_touch->>'utm_source', ''), 'direto') as origem,
    coalesce(nullif(p.analytics_last_touch->>'utm_campaign', ''), '(sem campanha)') as campanha,
    count(*) as pagamentos_aprovados,
    round(sum(coalesce(p.credito_valor_original, p.valor_total, p.total, 0)), 2) as faturamento
  from public.pedidos p
  where p.pedido_origem_id is null
    and coalesce(p.tipo_venda, 'online') = 'online'
    and p.pagamento_status = 'approved'
  group by 1, 2, 3
), chaves as (
  select dia, origem, campanha from sessoes
  union select dia, origem, campanha from eventos
  union select dia, origem, campanha from pedidos_criados
  union select dia, origem, campanha from pagamentos
)
select
  c.dia,
  c.origem,
  c.campanha,
  coalesce(s.sessoes, 0) as sessoes_loja,
  coalesce(s.sessoes_meta, 0) as sessoes_meta,
  coalesce(e.produtos_visualizados, 0) as produtos_visualizados,
  coalesce(e.adicoes_carrinho, 0) as adicoes_carrinho,
  coalesce(e.checkouts_iniciados, 0) as checkouts_iniciados,
  coalesce(e.pagamentos_iniciados, 0) as pagamentos_iniciados,
  coalesce(pc.pedidos_criados, 0) as pedidos_criados,
  coalesce(pg.pagamentos_aprovados, 0) as pagamentos_aprovados,
  coalesce(pg.faturamento, 0) as faturamento,
  coalesce(e.cliques_whatsapp, 0) as cliques_whatsapp,
  coalesce(e.cliques_instagram, 0) as cliques_instagram,
  round(100.0 * coalesce(e.sessoes_carrinho, 0) / nullif(coalesce(s.sessoes, 0), 0), 2) as taxa_visita_carrinho,
  round(100.0 * coalesce(e.sessoes_checkout, 0) / nullif(coalesce(e.sessoes_carrinho, 0), 0), 2) as taxa_carrinho_checkout,
  round(100.0 * coalesce(pg.pagamentos_aprovados, 0) / nullif(coalesce(e.sessoes_checkout, 0), 0), 2) as taxa_checkout_pagamento,
  round(100.0 * coalesce(pg.pagamentos_aprovados, 0) / nullif(coalesce(s.sessoes, 0), 0), 2) as taxa_visita_compra
from chaves c
left join sessoes s using (dia, origem, campanha)
left join eventos e using (dia, origem, campanha)
left join pedidos_criados pc using (dia, origem, campanha)
left join pagamentos pg using (dia, origem, campanha);

comment on view public.vw_funil_loja_diario is
