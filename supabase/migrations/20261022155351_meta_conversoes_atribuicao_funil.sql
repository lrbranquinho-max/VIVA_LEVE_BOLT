-- Mensuração própria da loja, atribuição first/last touch e base idempotente
-- para Meta Pixel + Conversions API. Alterações exclusivamente aditivas.

alter table public.loja_acessos
  add column if not exists user_id uuid references auth.users(id) on delete set null,
  add column if not exists utm_source text,
  add column if not exists utm_medium text,
  add column if not exists utm_campaign text,
  add column if not exists utm_content text,
  add column if not exists utm_term text,
  add column if not exists fbclid text,
  add column if not exists fbc text,
  add column if not exists fbp text,
  add column if not exists referrer text,
  add column if not exists landing_page text,
  add column if not exists ultima_pagina text,
  add column if not exists first_touch jsonb not null default '{}'::jsonb,
  add column if not exists last_touch jsonb not null default '{}'::jsonb,
  add column if not exists meta_consent boolean not null default false,
  add column if not exists atualizado_em timestamptz not null default now();

comment on table public.loja_acessos is
  'Sessões da loja com atribuição first/last touch, sem armazenar IP ou novos dados pessoais.';

create index if not exists loja_acessos_origem_campanha_idx
  on public.loja_acessos (utm_source, utm_campaign, acessado_em desc);
create index if not exists loja_acessos_user_idx
  on public.loja_acessos (user_id, acessado_em desc)
  where user_id is not null;

alter table public.pedidos
  add column if not exists analytics_sessao_id uuid references public.loja_acessos(sessao_id) on delete set null,
  add column if not exists analytics_first_touch jsonb not null default '{}'::jsonb,
  add column if not exists analytics_last_touch jsonb not null default '{}'::jsonb;

create index if not exists pedidos_analytics_sessao_idx
  on public.pedidos (analytics_sessao_id)
  where analytics_sessao_id is not null;

create table if not exists public.loja_eventos (
  id bigint generated by default as identity primary key,
  event_id uuid not null default gen_random_uuid(),
  event_name text not null check (event_name in (
    'store_visit', 'product_view', 'add_to_cart', 'checkout_started',
    'payment_started', 'purchase', 'whatsapp_click', 'instagram_click'
  )),
  sessao_id uuid references public.loja_acessos(sessao_id) on delete set null,
  user_id uuid references auth.users(id) on delete set null,
  produto_id bigint references public.produtos(id) on delete set null,
  pedido_id bigint references public.pedidos(id) on delete set null,
  pagina text,
  origem text not null default 'browser' check (origem in ('browser', 'server')),
  propriedades jsonb not null default '{}'::jsonb,
  ocorrido_em timestamptz not null default now(),
  criado_em timestamptz not null default now(),
  constraint loja_eventos_event_id_key unique (event_id),
  constraint loja_eventos_propriedades_objeto_check check (jsonb_typeof(propriedades) = 'object')
);

comment on table public.loja_eventos is
  'Funil interno idempotente da loja. Não armazena IP e não depende da Meta.';

create index if not exists loja_eventos_nome_data_idx
  on public.loja_eventos (event_name, ocorrido_em desc);
create index if not exists loja_eventos_sessao_data_idx
  on public.loja_eventos (sessao_id, ocorrido_em desc)
  where sessao_id is not null;
create index if not exists loja_eventos_pedido_idx
  on public.loja_eventos (pedido_id)
  where pedido_id is not null;
create index if not exists loja_eventos_produto_idx
  on public.loja_eventos (produto_id, ocorrido_em desc)
  where produto_id is not null;
create unique index if not exists loja_eventos_purchase_pedido_key
  on public.loja_eventos (pedido_id, event_name)
  where pedido_id is not null and event_name = 'purchase';

create table if not exists public.meta_capi_entregas (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.loja_eventos(event_id) on delete cascade,
  status text not null default 'pending' check (status in (
    'pending', 'processing', 'sent', 'waiting_configuration',
    'skipped_no_consent', 'error'
  )),
  tentativas integer not null default 0 check (tentativas >= 0),
  http_status integer,
  meta_trace_id text,
  ultimo_erro text,
  resposta_resumo jsonb not null default '{}'::jsonb,
  enviado_em timestamptz,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint meta_capi_entregas_event_id_key unique (event_id),
  constraint meta_capi_resposta_objeto_check check (jsonb_typeof(resposta_resumo) = 'object')
);

comment on table public.meta_capi_entregas is
  'Observabilidade da CAPI sem tokens, payload pessoal, e-mail, telefone ou IP.';

create index if not exists meta_capi_entregas_pendentes_idx
  on public.meta_capi_entregas (status, atualizado_em)
  where status in ('pending', 'waiting_configuration', 'error');

