create or replace function public.auditar_pedido_entrega()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_evento text;
  v_ator_tipo text;
begin
  if old.entregador_id is distinct from new.entregador_id then
    v_evento := case
      when old.entregador_id is null then 'atribuido'
      when new.entregador_id is null then 'atribuicao_removida'
      else 'reatribuido'
    end;
    v_ator_tipo := case
      when new.status = 'Entregue' and new.entrega_metodo_confirmacao = 'cliente' then 'client'
      when new.status = 'Entregue' and new.entrega_metodo_confirmacao = 'codigo_entregador' then 'delivery'
      else public.entrega_ator_tipo()
    end;

    insert into public.entregas_historico (
      pedido_id, evento, status_anterior, status_novo, entregador_anterior_id,
      entregador_novo_id, ator_id, ator_tipo
    ) values (
      new.id, v_evento, old.status, new.status, old.entregador_id,
      new.entregador_id, auth.uid(), public.entrega_ator_tipo()
    );
  end if;

  if old.status is distinct from new.status then
    v_evento := case
      when new.status = 'Saiu para Entrega' then 'saiu_para_entrega'
      when new.status = 'Entregue' then 'entregue'
      else 'status_alterado'
    end;
    insert into public.entregas_historico (
      pedido_id, evento, status_anterior, status_novo, entregador_anterior_id,
      entregador_novo_id, ator_id, ator_tipo, metodo_confirmacao
    ) values (
      new.id, v_evento, old.status, new.status, old.entregador_id,
      new.entregador_id, auth.uid(), v_ator_tipo, new.entrega_metodo_confirmacao
    );
  end if;
  return new;
end;
$$;

drop trigger if exists trg_pedidos_auditar_entrega on public.pedidos;
create trigger trg_pedidos_auditar_entrega
after update of status, entregador_id on public.pedidos
for each row execute function public.auditar_pedido_entrega();

create or replace function public.atribuir_entregador_pedido(
  p_pedido_id bigint,
  p_entregador_id uuid,
  p_observacoes text default null,
  p_janela text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_pedido public.pedidos%rowtype;
begin
  if not public.is_viva_leve_admin() then
    raise exception 'Acesso restrito a administradores.' using errcode = '42501';
  end if;

  select * into v_pedido from public.pedidos where id = p_pedido_id for update;
  if not found then raise exception 'Pedido não encontrado.' using errcode = 'P0002'; end if;
  if v_pedido.status = 'Entregue' then raise exception 'Pedido já entregue não pode ser reatribuído.'; end if;

  if p_entregador_id is not null and not exists (
    select 1
    from auth.users users
    join public.admin_usuario_roles roles on lower(roles.email) = lower(users.email)
    where users.id = p_entregador_id and roles.role = 'delivery' and roles.ativo = true
  ) then
    raise exception 'Entregador ativo não encontrado.' using errcode = 'P0002';
  end if;

  update public.pedidos
  set entregador_id = p_entregador_id,
      entrega_atribuida_em = case when p_entregador_id is null then null else now() end,
      entrega_observacoes = nullif(trim(p_observacoes), ''),
      entrega_janela = nullif(trim(p_janela), ''),
      status = case
        when p_entregador_id is null and status = 'Saiu para Entrega' then 'Em Preparo'
        else status
      end,
      updated_at = now()
  where id = p_pedido_id;
end;
$$;

create or replace function public.iniciar_entrega_pedido(p_pedido_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_pedido public.pedidos%rowtype;
begin
  if not public.is_viva_leve_delivery() then
    raise exception 'Acesso restrito a entregadores.' using errcode = '42501';
  end if;
  select * into v_pedido from public.pedidos where id = p_pedido_id for update;
  if not found or v_pedido.entregador_id is distinct from auth.uid() then
    raise exception 'Entrega não encontrada ou não atribuída a você.' using errcode = '42501';
  end if;
  if v_pedido.status not in ('Recebido', 'Em Preparo') then
    raise exception 'A entrega só pode ser iniciada após o pedido estar recebido ou em preparo.';
  end if;

  update public.pedidos
  set status = 'Saiu para Entrega', updated_at = now()
  where id = p_pedido_id and entregador_id = auth.uid();
end;
$$;

create or replace function public.confirmar_entrega_por_codigo(p_pedido_id bigint, p_codigo text)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_pedido public.pedidos%rowtype;
  v_hash bytea;
  v_tentativas integer;
begin
  if not public.is_viva_leve_delivery() then
    raise exception 'Acesso restrito a entregadores.' using errcode = '42501';
  end if;

  select * into v_pedido from public.pedidos where id = p_pedido_id for update;
  if not found or v_pedido.entregador_id is distinct from auth.uid() then
    raise exception 'Entrega não encontrada ou não atribuída a você.' using errcode = '42501';
  end if;
  if v_pedido.status = 'Entregue' or v_pedido.entrega_codigo_utilizado_em is not null then
    return jsonb_build_object('ok', false, 'message', 'Esta entrega já foi confirmada.');
  end if;
  if v_pedido.status <> 'Saiu para Entrega' or v_pedido.entrega_codigo_hash is null then
    return jsonb_build_object('ok', false, 'message', 'A entrega ainda não está em rota.');
  end if;
  if v_pedido.entrega_bloqueado_ate is not null and v_pedido.entrega_bloqueado_ate > now() then
    return jsonb_build_object('ok', false, 'message', 'Muitas tentativas. Aguarde 15 minutos e tente novamente.');
  end if;

  v_tentativas := case
    when v_pedido.entrega_bloqueado_ate is not null and v_pedido.entrega_bloqueado_ate <= now() then 0
    else v_pedido.entrega_tentativas_codigo
  end;
  v_hash := private.hash_codigo_entrega(trim(coalesce(p_codigo, '')), v_pedido.entrega_codigo_salt);

  if v_hash <> v_pedido.entrega_codigo_hash then
    v_tentativas := v_tentativas + 1;
    update public.pedidos
    set entrega_tentativas_codigo = v_tentativas,
        entrega_bloqueado_ate = case when v_tentativas >= 5 then now() + interval '15 minutes' else null end,
        updated_at = now()
    where id = p_pedido_id;
    insert into public.entregas_historico (
      pedido_id, evento, status_anterior, status_novo, entregador_anterior_id,
      entregador_novo_id, ator_id, ator_tipo, detalhes
    ) values (
      p_pedido_id, 'tentativa_codigo_invalido', v_pedido.status, v_pedido.status,
      v_pedido.entregador_id, v_pedido.entregador_id, auth.uid(), 'delivery',
      jsonb_build_object('tentativa', v_tentativas, 'bloqueado', v_tentativas >= 5)
    );
    return jsonb_build_object(
      'ok', false,
      'message', case when v_tentativas >= 5
        then 'Código inválido. Novas tentativas foram bloqueadas por 15 minutos.'
        else 'Código de confirmação inválido.' end
    );
  end if;

  update public.pedidos
  set status = 'Entregue',
      entregue_em = now(),
      entrega_metodo_confirmacao = 'codigo_entregador',
      entrega_confirmada_por = auth.uid(),
      entrega_codigo_utilizado_em = now(),
      updated_at = now()
  where id = p_pedido_id and status = 'Saiu para Entrega';

  return jsonb_build_object('ok', true, 'message', 'Entrega confirmada com sucesso.');
end;
$$;

