create or replace function public.preparar_codigo_status_entrega()
returns trigger
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_codigo text;
begin
  if new.status = 'Saiu para Entrega' and old.status is distinct from 'Saiu para Entrega' then
    if new.entregador_id is null then
      raise exception 'Atribua um entregador antes de iniciar a entrega.' using errcode = '23514';
    end if;
    new.entrega_codigo_salt := gen_random_uuid();
    v_codigo := private.codigo_entrega(new.id, new.entrega_codigo_salt);
    new.entrega_codigo_hash := private.hash_codigo_entrega(v_codigo, new.entrega_codigo_salt);
    new.entrega_codigo_gerado_em := now();
    new.entrega_codigo_utilizado_em := null;
    new.entrega_tentativas_codigo := 0;
    new.entrega_bloqueado_ate := null;
    new.saiu_entrega_em := coalesce(new.saiu_entrega_em, now());
  elsif new.status = 'Entregue' and old.status is distinct from 'Entregue' then
    new.entregue_em := coalesce(new.entregue_em, now());
    new.entrega_codigo_utilizado_em := coalesce(new.entrega_codigo_utilizado_em, now());
    new.entrega_codigo_hash := null;
    new.entrega_codigo_salt := null;
    new.entrega_bloqueado_ate := null;
  elsif old.status = 'Saiu para Entrega' and new.status not in ('Saiu para Entrega', 'Entregue') then
    new.entrega_codigo_hash := null;
    new.entrega_codigo_salt := null;
    new.entrega_codigo_utilizado_em := now();
    new.entrega_bloqueado_ate := null;
  end if;
  return new;
end;
$$;

