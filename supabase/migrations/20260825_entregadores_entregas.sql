create or replace function private.codigo_entrega(p_pedido_id bigint, p_salt uuid)
returns text
language plpgsql
stable
security definer
set search_path = private, extensions, pg_temp
as $$
declare
  v_segredo bytea;
  v_numero bigint;
begin
  select segredo into v_segredo from private.entrega_segredo where id = true;
  v_numero := (('x' || substr(encode(extensions.hmac(
    convert_to(p_pedido_id::text || ':' || p_salt::text, 'utf8'),
    v_segredo,
    'sha256'
  ), 'hex'), 1, 8))::bit(32)::bigint % 1000000);
  return lpad(v_numero::text, 6, '0');
end;
$$;

create or replace function private.hash_codigo_entrega(p_codigo text, p_salt uuid)
returns bytea
language plpgsql
stable
security definer
set search_path = private, extensions, pg_temp
as $$
declare
  v_segredo bytea;
begin
  select segredo into v_segredo from private.entrega_segredo where id = true;
  return extensions.hmac(
    convert_to(trim(p_codigo) || ':' || p_salt::text, 'utf8'),
    v_segredo,
    'sha256'
  );
end;
$$;

revoke all on function private.codigo_entrega(bigint, uuid) from public, anon, authenticated;
revoke all on function private.hash_codigo_entrega(text, uuid) from public, anon, authenticated;

